import type { Operator } from './operator';

/** Абзац — строка, список — массив строк. */
export type LegalBlock = string | string[];
export interface LegalSection {
  title: string;
  body: LegalBlock[];
}

const MISSING = '[не указано]';

function operatorLine(op: Operator): string {
  const parts = [op.name ?? MISSING, op.registry, op.address ? `адрес: ${op.address}` : `адрес: ${MISSING}`];
  return parts.filter((p): p is string => p !== null).join(', ');
}

const contact = (op: Operator): string => op.email ?? MISSING;

